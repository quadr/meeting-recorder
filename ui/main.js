// Суффикс "(сейчас недоступен)" к имени устройства ставит не эта функция —
// она его только снимает, обратно перед тем, как отправить имя в Rust.
// Сравнение по обеим языковым версиям (i18n.tBoth), а не только по текущему
// языку интерфейса: иначе на английском интерфейсе суффикс перестал бы
// вырезаться.
function без_суффикса_недоступности(текст) {
  const { ru, en } = i18n.tBoth("permission.deviceGone");
  for (const суффикс of [ru, en]) {
    if (суффикс && текст.endsWith(суффикс)) return текст.slice(0, -суффикс.length);
  }
  return текст;
}

