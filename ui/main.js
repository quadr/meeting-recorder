// Пока окно скрыто в трее, WebView2 иногда не перерисовывает свои
// абсолютно позиционированные слои (заливка полоски через clip-path, пиковый
// маркер) — сам DOM и custom-property уже верные (обновляются событиями и
// тогда, когда окно не в фокусе), а нарисованный кадр остаётся старым до
// первого события, которое их снова тронет. Заливка потом сама «отпускает»
// с первым же levels, а маркер никто больше не трогает — так и висит
// неправильно нарисованным. display:none/restore синхронно, без паузы на
// отрисовку между ними, поэтому мигания не видно, а слой перерисовывается
// с нуля.
//
// Метров теперь два комплекта — полные в настройках и узкие в панели «идёт
// запись», — и баг одинаково цепляет оба, поэтому перерисовываются все.
function форсировать_перерисовку_метров() {
  for (const el of document.querySelectorAll(".disc")) {
    el.style.display = "none";
    void el.offsetHeight;
    el.style.display = "";
  }
}

