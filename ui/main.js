// Порядок здесь — не вкусовщина. Сначала подписки, потом снимок: подписавшись
// первыми, мы не пропустим изменение, случившееся во время запроса, а снимок
// следом покажет то, что случилось ДО подписки. Наоборот — оставило бы дырку
// ровно между двумя шагами.
//
// Снимок нужен именно потому, что Tauri не буферизует события: аудио-поток
// живёт с setup(), эта страница загружается позже (а после перезагрузки окна —
// намного позже), и всё, что он успел сообщить до нас, мы можем только спросить.
async function старт() {
  // Словарь и язык обязаны быть готовы раньше первой отрисовки — иначе все
  // t() ниже вернули бы голые ключи вместо текста.
  await window.i18n.ready;
  window.i18n.applyStatic();
  // Заголовок нативного окна ставит конфиг (tauri.conf.json, статично и
  // по-английски — он не умеет читать словарь), а на реальный язык доводит
  // его этот вызов.
  getCurrentWindow()
    .setTitle(i18n.t("app.windowMain"))
    .catch(() => {});
  отрисовать_версию();
  отрисовать_контакты("contacts-design", "contacts-design-soon", КОНТАКТЫ_ДИЗАЙН);
  отрисовать_контакты("contacts-code", "contacts-code-soon", КОНТАКТЫ_РАЗРАБОТКА);
  отрисовать_поддержку();

  await listen("state", (e) => применить_состояние(e.payload));
  await listen("callabo-settings-warning", (e) => показать_ошибку(i18n.t("callabo.error"), e.payload));
  await listen("callabo-progress", (e) => {
    const key = ключ_записи(e.payload.folder, e.payload.base);
    if (e.payload.stage === "done") callaboUploads.delete(key);
    else callaboUploads.set(key, e.payload.stage);
    обновить_список();
  });
  // Само по себе событие ничего не показывает: строку взвода ставит
  // применить_состояние в момент перехода в «armed». Здесь только запоминаем,
  // кого услышали, — состояние придёт отдельным событием следом.
  await listen("ask", (e) => {
    const имя = String(e.payload ?? "");
    кто_звонит = ЗВОНИЛКИ[имя] ?? "";
  });
  await listen("error", (e) => показать_ошибку(i18n.t("error.audio"), e.payload));
  await listen("fatal", (e) => показать_фатальную(String(e.payload)));
  await listen("device-warning", (e) => показать_предупреждение_устройства(e.payload));
  await listen("mic-deferred", (e) => показать_отложенность(Boolean(e.payload)));
  await listen("no-system-audio", (e) =>
    показать_отсутствие_системного_звука(e.payload),
  );
  await listen("levels", (e) => применить_уровни(e.payload));
  await listen("update-available", (e) => показать_обновление(e.payload));
  try {
    const снимок = await invoke("get_state");
    применить_состояние(снимок.state);
    if (снимок.fatal) показать_фатальную(снимок.fatal);
    показать_предупреждение_устройства(снимок.device_warning);
    показать_отложенность(Boolean(снимок.mic_deferred));
    // Через снимок, а не только по событию: отказ случается в setup(), то есть
    // раньше, чем webview успевает подписаться, — и после перезагрузки
    // страницы событие уже не повторится.
    показать_отсутствие_системного_звука(снимок.no_system_audio);
  } catch (e) {
    показать_ошибку(i18n.t("error.state"), e);
  }

  // Обновление — тем же приёмом, что снимок состояния выше: проверка идёт в
  // фоне с первой секунды, и её событие могло уйти до подписки. Отказ здесь
  // молчит: баннер обновления — не то, ради чего показывать ошибку.
  try {
    показать_обновление(await invoke("update_status"));
  } catch {
    показать_обновление(null);
  }

  // раз, дорожка — по разу на дорожку, а сам опрос шлюза длится часами молча.
  // Без этого таймера подпись «12 мин» замерла бы на значении, которое было в
  // момент прихода события, и врала бы тем сильнее, чем дольше идёт работа.
  // Полминуты — с запасом: подпись всё равно округлена до минут.
  // Безусловно, хотя применить_состояние выше могло уже дёрнуть список: в Armed
  // и в записи оно этого не делает, а показать прошлые записи надо в любом
  // состоянии. Лишний read_dir на старте дешевле, чем связка с чужим условием,
  // которая молча оставит список пустым, если то условие однажды поменяется.
  обновить_список();
  обновить_устройства();
  const callaboConfig = await invoke("get_config");
  callaboUI.initialize(callaboConfig.callabo_workspace ?? null)
    .catch((e) => показать_ошибку(i18n.t("callabo.error"), e));
}

