// что уже вычищено, вычищено не мгновенно по смене настройки, а на следующем
// суточном проходе.
// ─────────────────────────────────────────────────────────────────────────────
// Кнопки
//
// Кнопка гаснет по клику, а не когда придёт ответ: за секунду между кликом и
// ответом по ней успевают нажать трижды.
async function нажать(кнопка, подпись_узел, подпись, действие) {
  кнопка.disabled = true;
  const прежняя = подпись_узел?.textContent;
  if (подпись_узел) подпись_узел.textContent = подпись;
  try {
    await действие();
  } finally {
    кнопка.disabled = false;
    // Подпись возвращаем только если состояние не сменилось: при удачном старте
    // кнопку записи уже заменила панель «идёт запись», и трогать её незачем.
    if (подпись_узел && подпись_узел.textContent === подпись) {
      подпись_узел.textContent = прежняя;
    }
  }
}

