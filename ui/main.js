// Состояние машины
//
// Таймер записи считается здесь, а не приходит из бэкенда: момента начала в
// снимке (`status::Snapshot`) нет. Поэтому число показывается только тогда,
// когда окно своими глазами видело переход в запись. Открыли окно из трея
// посреди встречи — таймера нет, но подпись «Запись идёт» есть: лучше не
// показать число, чем показать выдуманное.
let запись_началась = null;
let тик_таймера = null;
let первое_состояние = true;

function формат_таймера(мс) {
  const всего = Math.floor(мс / 1000);
  const ч = Math.floor(всего / 3600);
  const м = Math.floor((всего % 3600) / 60);
  const с = всего % 60;
  const мм_сс = `${String(м).padStart(2, "0")}:${String(с).padStart(2, "0")}`;
  return ч ? `${ч}:${мм_сс}` : мм_сс;
}

function обновить_таймер() {
  if (запись_началась == null) return;
  $("rec-timer").textContent = формат_таймера(Date.now() - запись_началась);
}

function запустить_таймер(известно_начало) {
  остановить_таймер();
  запись_началась = известно_начало ? Date.now() : null;
  $("rec-timer").hidden = !известно_начало;
  if (!известно_начало) return;
  обновить_таймер();
  тик_таймера = setInterval(обновить_таймер, 1000);
}

function остановить_таймер() {
  if (тик_таймера != null) clearInterval(тик_таймера);
  тик_таймера = null;
  запись_началась = null;
  $("rec-timer").hidden = true;
}

let предыдущее_состояние = null;

function применить_состояние(s) {
  const было_записью = предыдущее_состояние === "recording";
  const стало_записью = s === "recording";

  // Строка взвода живёт ровно столько, сколько Armed: ушла сессия или пришёл
  // ответ — она обязана исчезнуть сама, иначе на экране останется ожидание
  // ответа, которого уже никто не ждёт.
  const стало_взводом = s === "armed";
  слот("s-ask", стало_взводом);
  $("no").disabled = false;

  if (стало_взводом && предыдущее_состояние !== "armed") {
    // Текст ставится здесь, а не по событию `ask` и не в разметке: живая
    // область (role="status") озвучивает СМЕНУ текста, а не то, что готовый
    // текст стал видимым, — иначе появление взвода прошло бы молча.
    $("ask-q").textContent = кто_звонит
      ? i18n.t("state.armedApp", { app: кто_звонит })
      : i18n.t("state.armed");
    // Фокус переезжает на кнопку записи — во взводе это и есть ответ «да».
    // Ровно в момент перехода, а не на каждое событие состояния: иначе он
    // выдёргивался бы из поля правки имени и из настроек.
    if (!правка_идёт && !фатально) {
      // Слот только что получил класс `open`, но в дереве отрисовки кнопка ещё
      // `visibility: hidden` — а невидимому элементу движок фокус не даёт,
      // молча. Чтение offsetHeight заставляет пересчитать стили здесь и
      // сейчас; тот же приём стоит в открыть_меню по той же причине.
      void $("rec-btn").offsetHeight;
      $("rec-btn").focus();
    }
  } else if (!стало_взводом) {
    кто_звонит = "";
  }

  слот("s-record", !стало_записью);
  слот("s-recpanel", стало_записью);

  if (стало_записью && !было_записью) {
    // Первое применение состояния — это снимок из get_state: он говорит «идёт
    // запись», но не говорит, когда она началась.
    запустить_таймер(!первое_состояние);
    $("rec-panel").classList.remove("stopping");
    $("stop-btn").disabled = false;
    $("stop-btn-label").textContent = i18n.t("record.stop");
    // Подпись ставится отсюда, а не стоит в разметке: живая область
    // (role="status" у #rec-lbl) озвучивает смену текста, а не то, что
    // готовый текст стал видимым. Статичная подпись здесь молчала бы.
    $("rec-lbl").textContent = i18n.t("state.recording");
  } else if (!стало_записью && было_записью) {
    остановить_таймер();
    $("rec-lbl").textContent = "";
  }

  if (!стало_записью) {
    $("rec-btn").disabled = фатально;
    $("rec-btn-label").textContent = i18n.t("record.start");
  }

  предыдущее_состояние = s;
  первое_состояние = false;

  if (s !== "recording" && s !== "armed") обновить_список();
  if (s === "idle" && !проверка_идёт) {
    // Без явного сброса пик просто «сполз» бы на пару дБ (обновить_пик вызовется
    // один раз, а не по тику) и завис — вместо мгновенного возврата к -∞.
    сбросить_пики();
    применить_уровни({ mic: 0, system: 0, monitoring: false });
  }
}

// Часть подписей внутри применить_состояние ставится только на переходе
// («стало_записью && !было_записью» и подобные), а не на каждый вызов —
// иначе повторный вызов с тем же состоянием заново стартовал бы таймер
// записи. Смене языка нужно освежить именно эти подписи, не трогая таймер,
// поэтому она не зовёт применить_состояние заново, а расставляет тексты сюда
// напрямую — по тому же условию, но без побочных эффектов.
function обновить_подписи_состояния() {
  if (предыдущее_состояние === "recording") {
    $("stop-btn-label").textContent = i18n.t("record.stop");
    $("rec-lbl").textContent = i18n.t("state.recording");
  } else {
    $("rec-btn-label").textContent = i18n.t("record.start");
  }
  if (предыдущее_состояние === "armed") {
    $("ask-q").textContent = кто_звонит
      ? i18n.t("state.armedApp", { app: кто_звонит })
      : i18n.t("state.armed");
  }
}

// Перерисовать всё, что уже на экране, на новый язык — без перезапуска и без
// повторной загрузки словаря (он уже в памяти, см. i18n.js). Собирает вместе
// ровно то, что старт() делает при первой загрузке страницы: статичную
// разметку, заголовок окна, список, выпадашки настроек и баннеры, которые
// сейчас показаны, — источник данных для баннеров тот же снимок get_state,
// что и на старте, а не запомненные заранее строки.
async function обновить_после_смены_языка() {
  window.i18n.applyStatic();
  getCurrentWindow()
    .setTitle(i18n.t("app.windowMain"))
    .catch(() => {});
  // Версия собрана через t() с подстановкой — applyStatic() её не трогает,
  // обновляем сами.
  отрисовать_версию();
  // Открытое меню действия — не переводим на месте: у него нет своего
  // «источника правды» отдельно от разметки, которую собрал собрать_меню на
  // старом языке. Закрыть безопаснее, чем показать наполовину переведённое;
  // открыть его на новом языке можно тем же кликом.
  закрыть_меню(false, true);
  обновить_подписи_состояния();
  try {
    const снимок = await invoke("get_state");
    if (снимок.fatal) показать_фатальную(снимок.fatal);
    показать_предупреждение_устройства(снимок.device_warning);
    показать_отложенность(Boolean(снимок.mic_deferred));
    показать_отсутствие_системного_звука(снимок.no_system_audio);
  } catch (e) {
    показать_ошибку(i18n.t("error.state"), e);
  }
  обновить_список();
  обновить_устройства();
  форсировать_перерисовку_метров();
}

// ─────────────────────────────────────────────────────────────────────────────
// Переключение экранов
//
// Стек, не два жёстко зашитых имени: список → настройки → (о разработчиках |
// поддержать). «Назад» снимает верхний экран стека и показывает тот, что под
// ним, — из «о разработчиках» это настройки, а не всегда список. Библиотека
// тут не нужна — стек это обычный массив.
const ЭКРАНЫ = ["list", "settings", "about", "support"];
let стек_экранов = ["list"];

function показать_экран(имя) {
  закрыть_меню(false, true);
  for (const s of ЭКРАНЫ) {
    // Не `hidden`, а классы: уехавший экран обязан остаться в документе на
    // время перехода, иначе двигаться нечему. Из обхода табом его выводит
    // `visibility` в стилях, погашенная с задержкой на длину перехода.
    const активен = s === имя;
    $(`screen-${s}`).classList.toggle("off", !активен);
    // Слева уезжает то, что осталось в стеке (туда ведёт «назад»), справа —
    // то, что ещё не открыто или только что закрылось назад. Экран может
    // сыграть обе роли в разных переходах (настройки — «впереди» списка, но
    // «позади» экрана «о разработчиках»), поэтому класс не привязан к имени
    // экрана, а пересчитывается каждый раз по актуальному стеку.
    $(`screen-${s}`).classList.toggle("off-left", !активен && стек_экранов.includes(s));
    $(`screen-${s}`).classList.toggle("off-right", !активен && !стек_экранов.includes(s));
  }
  if (имя === "settings") {
    обновить_устройства();
    форсировать_перерисовку_метров();
  }
}

// Вперёд — на экран, которого ещё не было в стеке.
function перейти_на(имя) {
  стек_экранов.push(имя);
  показать_экран(имя);
}

// Назад — туда, откуда пришли. Список всегда остаётся на дне стека: с него
// возвращаться уже некуда.
function вернуться_назад() {
  if (стек_экранов.length > 1) стек_экранов.pop();
  показать_экран(стек_экранов[стек_экранов.length - 1]);
}

