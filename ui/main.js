// Дата и время начала — из префикса имени. Другого источника нет: бэкенд
// отдаёт только имя, папку, размер и длительность.
function момент_записи(имя) {
  const m = /^(\d{4})-(\d{2})-(\d{2})_(\d{2})-(\d{2})/.exec(имя);
  if (!m) return null;
  return new Date(+m[1], +m[2] - 1, +m[3], +m[4], +m[5]);
}

function начало_суток(d) {
  const к = new Date(d);
  к.setHours(0, 0, 0, 0);
  return к;
}

// Месяцы и склонение дат — системным Intl.DateTimeFormat по текущему языку,
// а не ручным списком: список месяцев жил бы только для одного языка и
// разъезжался бы с английским. `long` даёт «2 сентября» по-русски и
// «September 2» по-английски — порядок день/месяц Intl сам берёт из языка.
function ярлык_дня(дата) {
  if (!дата) return i18n.t("date.unknown");
  const сегодня = начало_суток(new Date());
  const день = начало_суток(дата);
  const разница = Math.round((сегодня - день) / 86400000);
  if (разница === 0) return i18n.t("date.today");
  if (разница === 1) return i18n.t("date.yesterday");
  const опции = { day: "numeric", month: "long" };
  if (день.getFullYear() !== сегодня.getFullYear()) опции.year = "numeric";
  return new Intl.DateTimeFormat(i18n.lang, опции).format(день);
}

// timeStyle: "short" — это 24-часовой формат для русского языка и AM/PM для
// английского, оба системные: Intl решает это сам по локали, а не по нашему
// выбору.
function чч_мм(дата) {
  return new Intl.DateTimeFormat(i18n.lang, { timeStyle: "short" }).format(дата);
}

// Intl.DateTimeFormat.formatRange появился не во всех версиях движка —
// используем его, когда есть, иначе склеиваем через "–" сами.
function промежуток(начало, секунды) {
  if (!начало) return "";
  const конец = new Date(начало.getTime() + секунды * 1000);
  const формат = new Intl.DateTimeFormat(i18n.lang, { timeStyle: "short" });
  if (typeof формат.formatRange === "function") {
    return формат.formatRange(начало, конец);
  }
  return `${формат.format(начало)}–${формат.format(конец)}`;
}

function длительность(секунды) {
  if (!секунды) return i18n.t("duration.underMinute");
  const минуты = Math.round(секунды / 60);
  if (минуты < 1) return i18n.t("duration.underMinute");
  if (минуты < 60) return i18n.t("duration.minutes", { n: минуты });
  const часы = Math.floor(минуты / 60);
  const остаток = минуты % 60;
  return остаток
    ? i18n.t("duration.hoursMinutes", { h: часы, m: остаток })
    : i18n.t("duration.hours", { n: часы });
}

